(() => {
  const KEY = "ft-webui-lang";
  // the language the OS/browser asks for, until someone picks one here
  const prefers = [...(navigator.languages || []), navigator.language || ""];
  let lang = prefers.some((l) => l.toLowerCase().startsWith("ja")) ? "ja" : "en";
  try { const saved = localStorage.getItem(KEY); if (saved === "ja" || saved === "en") lang = saved; } catch {}

  const t = (key, vars) => {
    let s = (I18N[lang] || I18N.ja)[key] ?? I18N.ja[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };

  function applyStatic(root = document) {
    for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
    for (const el of root.querySelectorAll("[data-i18n-ph]")) el.placeholder = t(el.dataset.i18nPh);
    if (root === document) document.documentElement.lang = lang;
  }

  window.FTI18N = {
    t, applyStatic,
    add(ja, en) { Object.assign(I18N.ja, ja); Object.assign(I18N.en, en); },
    get lang() { return lang; },
    set(next) {
      if (next !== "ja" && next !== "en") return;
      try { localStorage.setItem(KEY, next); } catch {}
      location.reload();
    },
  };
})();
